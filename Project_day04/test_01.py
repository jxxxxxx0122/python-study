print("'100' == '100' 吗 : ", '100' == '100')
print("100 != 100 吗 : ", 100 != 100)

print("100 < 100 吗 : ", 100 < 100)
print("100 <= 100 吗 : ", 100 <= 100)

print("100 > 100 吗 : ", 100 > 100)
print("100 >= 100 吗 : ", 100 >= 100)


# # 逻辑运算符 ---> and(与)  or(或)  not(非)
# 案例：键盘输入一个数字，判断是否在 10-20之间
num = int(input("请输入一个整数: "))

print(f"{num}在10-20之间: ",10 <= num <= 20)

#案例: 键盘输入一个数字，判断是否不在10-20之间
